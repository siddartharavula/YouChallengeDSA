const getPlatform = (url) => {
  if (url.includes("leetcode.com")) return "leetcode";
  if (url.includes("geeksforgeeks.org")) return "geeksforgeeks";
  if (url.includes("smartinterviews.in")) return "smartinterviews";
  return "unknown";
};

// Remove duplicates while preserving first occurrence.
const seen = new Set();

const dsaPractice = topics.map(({ topic, slug, problems }) => ({
  topic,
  slug,

  problems: problems
    .filter((problem) => {
      const normalized = problem.link
        .replace(/\/description\/?$/, "")
        .replace(/\/+$/, "")
        .toLowerCase();

      if (seen.has(normalized)) {
        return false;
      }

      seen.add(normalized);
      return true;
    })
    .map((problem) => ({
      name: problem.name,
      link: problem.link,
      platform: getPlatform(problem.link),
    })),
}));

module.exports = dsaPractice;